// =============================================================================
// GUTTERCAPS — команды (crew), docs/16 §5.6
// -----------------------------------------------------------------------------
// Команда — это имя, состав и общий сегмент стены. Ничего из этого не продаёт
// охват: решение 6 (§0.3) запрещает покупать место на стене, поэтому сегмент
// занимается ровно теми же правилами активности, что обычный слот (§3.4).
//
// Два решения, которые здесь приняты раз и навсегда:
//
// 1. **Имя команды — это модель хендла.** Тот же алфавит, та же уникальность
//    без регистра, тот же блоклист, те же 30 дней на переименование и те же
//    90 дней карантина освобождённого имени. Отдельная модель имён стоила бы
//    отдельной модерации, а она у города уже одна (§3.4).
// 2. **Командный результат считается по N лучшим, а не по всем.** Иначе команда
//    из десяти человек побеждала бы команду из пяти одной только численностью,
//    и «набрать побольше теплых тел» стало бы стратегией. Считаем пятерых
//    лучших: состав важнее размера.
// =============================================================================

import { LINE_TIERS, type LineTier } from './runs.ts';

export const CREW = {
  /** Минимум состава: меньше пяти — это не команда, а чат. */
  minMembers: 5,
  /** Максимум: десять человек совещаются, двадцать — уже не собираются. */
  maxMembers: 10,
  /** Сколько лучших заездов участников идут в командный результат недели. */
  boardCountingMembers: 5,
  /** Сегмент стены команды (docs/16 §5.6): 20 слотов на район. */
  wallSegmentSlots: 20,
  /** Имя: как у хендла — 3–16 символов [a-zA-Z0-9_]. */
  nameMin: 3,
  nameMax: 16,
  /** Переименование — раз в 30 дней (как у хендла), и оно платное. */
  renameCooldownDays: 30,
  /** Освобождённое имя возвращается в оборот через 90 дней. */
  nameQuarantineDays: 90,
  /** Сколько команд видно на доске недели. */
  boardTop: 50,
  /** Ежемесячный конкурс: призовые места. Призы — косметика, никогда не $CG. */
  monthlyContestPlaces: 3,
} as const;

/** Тот же алфавит, что у хендла: одна модель имён на весь город. */
export const CREW_NAME_RE = /^[a-zA-Z0-9_]{3,16}$/;

/** Ключ уникальности: `Gutter` и `gutter` — одно имя. */
export const crewNameKey = (name: string): string => name.trim().toLowerCase();

/**
 * Пороги командного результата — пороги заезда, умноженные на число зачитываемых
 * участников: «пятеро доехали до золота» и есть командное золото. Пороги не
 * придуманы рядом с числами заезда, а произведены от них, поэтому при правке
 * LINE_TIERS командные пороги поедут вместе с ними.
 */
/**
 * Пороги командного результата — функция, а не константа уровня модуля.
 *
 * Почему так: `packages/economy` импортируется клиентом через общий баррель
 * `index.ts`. Константа, посчитанная при загрузке модуля (`LINE_TIERS.map(...)`),
 * — это побочный эффект уровня модуля, и Rollup из-за него не может выбросить
 * файл из entry-графа: вместе с командой в критический путь первого экрана
 * уезжал симулятор линии целиком (+3,5 КБ gz, замер `npm run bundle:check`).
 * Ленивая функция того же стоит: считается один раз, при первом вызове.
 */
let cachedTiers: ReadonlyArray<{ tier: LineTier; score: number }> | null = null;
export function crewTiers(): ReadonlyArray<{ tier: LineTier; score: number }> {
  if (cachedTiers) return cachedTiers;
  cachedTiers = LINE_TIERS.map((t) => ({ tier: t.tier, score: t.score * CREW.boardCountingMembers }));
  return cachedTiers;
}

export function crewTier(score: number): LineTier {
  for (const t of crewTiers()) if (score >= t.score) return t.tier;
  return 'none';
}

/**
 * Очки команды за неделю: сумма лучших заездов `counting` лучших участников.
 *
 * Сумма, а не среднее, иначе команда из пяти человек получала бы то же, что
 * команда из десяти, и большой состав не давал бы ничего. Пятеро лучших —
 * потолок вклада состава: шестой участник команду уже не поднимает.
 */
export function crewWeekScore(bestScores: readonly number[], counting = CREW.boardCountingMembers): number {
  return [...bestScores].sort((a, b) => b - a).slice(0, counting).reduce((a, b) => a + b, 0);
}

/**
 * Команда считается «полной» — то есть участвует в командной доске — только с
 * `minMembers` участников, у каждого из которых есть заезд на этой неделе.
 * Правило нужно, чтобы доска не превращалась в доску одиночек с вывеской.
 */
export function crewCounts(membersWithRuns: number, members = membersWithRuns): boolean {
  return members >= CREW.minMembers && membersWithRuns >= CREW.minMembers;
}
